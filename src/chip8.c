#include "chip8.h"
#include <stdio.h>
#include <string.h>
#include <time.h>

static const uint8_t FONTSET[80] = {
    0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
    0x20, 0x60, 0x20, 0x20, 0x70, // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
    0x90, 0x90, 0xF0, 0x10, 0x10, // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
    0xF0, 0x10, 0x20, 0x40, 0x40, // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90, // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
    0xF0, 0x80, 0x80, 0x80, 0xF0, // C
    0xE0, 0x90, 0x90, 0x90, 0xE0, // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
    0xF0, 0x80, 0xF0, 0x80, 0x80, // F
};

void chip8_init(chip8_t *cpu) {
    memset(cpu, 0, sizeof(*cpu));
    memcpy(cpu->memory + CHIP8_FONT_START, FONTSET, sizeof(FONTSET));
    cpu->pc = CHIP8_ROM_START;
    cpu->rng_state = (uint32_t)time(NULL) | 1u; // xorshift needs a nonzero seed
}

int chip8_load_rom(chip8_t *cpu, const char *path) {
    FILE *f = fopen(path, "rb");
    if (!f) {
        fprintf(stderr, "chip8_load_rom: cannot open %s\n", path);
        return -1;
    }
    size_t max = CHIP8_MEM_SIZE - CHIP8_ROM_START;
    size_t n = fread(cpu->memory + CHIP8_ROM_START, 1, max, f);
    fclose(f);
    if (n == 0) {
        fprintf(stderr, "chip8_load_rom: %s is empty or unreadable\n", path);
        return -1;
    }
    return 0;
}
